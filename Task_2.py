# Task 2: Rectangle area
length = input("Введите длину прямоугольника: ")  # the length of the rectangle
width = input("Введите ширину прямоугольника: ")  # the width of the rectangle
area = int(length) * int(width)  # the area of the rectangle
print("Площадь прямоугольника:", area)  # output the result
